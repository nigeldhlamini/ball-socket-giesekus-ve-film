def _tex_escape(s: str) -> str:
    """Escape TeX actives in free text lifted out of a JSON config."""
    for a, b in ((chr(92), r"\textbackslash{}"), ("&", r"\&"),
                 ("%", r"\%"), ("$", r"\$"), ("#", r"\#"),
                 ("_", r"\_"), ("{", r"\{"), ("}", r"\}"),
                 ("~", r"\textasciitilde{}"),
                 ("^", r"\textasciicircum{}")):
        s = s.replace(a, b)
    return s


def _sha(p: pathlib.Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()[:16]


def _classify(row_g1, row_g2, row_g3) -> str:
    """Strict single-constraint classification: a sample binds constraint c
    when c is violated and the others are not; 'multi' when more than one is.
    Identical in form to the slipper convention of Chapter 7."""
    viol = [n for n, g in (("g1", row_g1), ("g2", row_g2), ("g3", row_g3))
            if g is not None and np.isfinite(g) and g < 0]
    if not viol:
        return "none"
    return viol[0] if len(viol) == 1 else "multi"


