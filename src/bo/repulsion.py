"""Stage B: post-hoc performance-space coverage repulsion for the BO loop.

Stage B addresses the cluster-on-subset pathology documented in the
critical review: BO observations sit near the AR boundary but cluster on
a subset, leaving gaps that random sampling would by chance cover. The
remedy is to penalise candidate points whose projection (under the
regression-GP posterior means) lands near already-densely-sampled regions
of performance space.

Augmented acquisition (per the prompt):

  log a(x) = log H(x) + log P_cls(x) - kappa * log rho(y_hat(x); Y_train)

where:
  - H(x) is the entropy of the classifier-GP at x.
  - P_cls(x) is the classifier-GP probability of convergence at x.
  - y_hat(x) is the regression-GP posterior mean projected onto the
    active performance plane.
  - rho is a kernel density estimate of training-point density in the
    active performance plane (scipy.stats.gaussian_kde, Silverman bw,
    recomputed every 10 BO iterations and cached).
  - kappa is the repulsion weight (default 0.5, configurable).

Implementation choice: the repulsion is applied as a POST-HOC PENALTY on
a candidate batch sampled from the entropy-only acquisition. This avoids
distorting the L-BFGS-B optimisation inside AcquisitionManager.optimize
and is the simplest way to keep Stages A/C unchanged. The candidate batch
is generated by Sobol sampling + filtering by P_joint >= 0.5; the top-K
by log a (entropy + classifier prob) are re-ranked by the augmented
acquisition; the best penalised candidate is returned.

Per-projection rotation: the active projection is selected per BO
iteration in a round-robin schedule across the four canonical
projections defined in src/bo/boundary.py. This keeps the schedule
deterministic and balanced.

Cache: the KDE is recomputed every 10 iterations and the result is
stored on the ranker; calls between refits reuse the cached KDE.
"""
from __future__ import annotations

import dataclasses
import pathlib
import sys
from typing import Optional

import numpy as np
import torch
from scipy.stats import gaussian_kde

_REPO = pathlib.Path(__file__).resolve().parents[2]
if str(_REPO) not in sys.path:
    sys.path.insert(0, str(_REPO))

from src.bo.boundary import (  # noqa: E402
    CANONICAL_PROJECTIONS, ProjectionSpec, _analytic_field,
)


@dataclasses.dataclass
class RepulsionConfig:
    kappa: float = 0.5
    schedule: str = "round_robin"  # only "round_robin" supported for now
    n_candidates: int = 2048
    top_k: int = 64
    kde_refit_every: int = 10
    p_threshold: float = 0.5
    projections: tuple[ProjectionSpec, ...] = CANONICAL_PROJECTIONS

    @property
    def n_projections(self) -> int:
        return len(self.projections)


class RepulsionRanker:
    """Stateful Stage B ranker. Holds the per-projection KDE cache and the
    round-robin schedule counter."""

    def __init__(self, config: RepulsionConfig, surrogates):
        self.config = config
        self.surrogates = surrogates
        self._iter = 0
        # KDE cache: keyed on projection name
        self._kde: dict[str, gaussian_kde] = {}
        self._kde_n_train: dict[str, int] = {}
        self._kde_last_refit_iter: dict[str, int] = {}

    def active_projection(self, iteration: int) -> ProjectionSpec:
        """Return the projection for this iteration under the schedule."""
        if self.config.schedule == "round_robin":
            idx = iteration % self.config.n_projections
            return self.config.projections[idx]
        raise ValueError(f"unknown schedule {self.config.schedule!r}")

    def _project_training_points(
        self, spec: ProjectionSpec, X_train_unit: np.ndarray,
        Y_train: dict[str, np.ndarray],
        feasible: np.ndarray,
    ) -> np.ndarray:
        """Return the (n_feas, 2) training-point coordinates in the projection."""
        def _field(name: str, source: str) -> np.ndarray:
            if source == "analytic":
                return _analytic_field(name, X_train_unit)
            return Y_train[name]
        x_v = _field(spec.x_field, spec.x_field_source)
        y_v = _field(spec.y_field, spec.y_field_source)
        mask = feasible & np.isfinite(x_v) & np.isfinite(y_v)
        return np.column_stack([x_v[mask], y_v[mask]])

    def _maybe_refit_kde(
        self, spec: ProjectionSpec, iteration: int,
        X_train_unit: np.ndarray,
        Y_train: dict[str, np.ndarray],
        feasible: np.ndarray,
    ) -> Optional[gaussian_kde]:
        """Refit the KDE if cache is stale; return the current KDE."""
        last = self._kde_last_refit_iter.get(spec.name, -10 ** 9)
        if (iteration - last) < self.config.kde_refit_every \
                and spec.name in self._kde:
            return self._kde[spec.name]
        pts = self._project_training_points(spec, X_train_unit, Y_train, feasible)
        if len(pts) < 4:
            self._kde[spec.name] = None  # mark as too-few-points
            self._kde_n_train[spec.name] = len(pts)
            self._kde_last_refit_iter[spec.name] = iteration
            return None
        # KDE in log-coordinates for projections with log axes, to
        # avoid extreme bandwidth artefacts.
        log_axes = (spec.x_field in ("h_min", "P_loss", "Q_leak"),
                    spec.y_field in ("h_min", "P_loss", "Q_leak"))
        pts_kde = pts.astype(np.float64).copy()
        if log_axes[0]:
            pts_kde[:, 0] = np.log10(np.clip(pts_kde[:, 0], 1e-300, None))
        if log_axes[1]:
            pts_kde[:, 1] = np.log10(np.clip(pts_kde[:, 1], 1e-300, None))
        kde = gaussian_kde(pts_kde.T, bw_method="silverman")
        self._kde[spec.name] = kde
        self._kde_n_train[spec.name] = len(pts)
        self._kde_last_refit_iter[spec.name] = iteration
        return kde

    def _project_candidates(
        self, spec: ProjectionSpec, X_unit_torch: torch.Tensor,
    ) -> np.ndarray:
        """Project candidate (M, d) tensor onto the spec's plane using
        the regression-GP posterior means (or analytic for F_applied)."""
        from src.bo.boundary import _evaluate_gp_grid
        grid = _evaluate_gp_grid(
            self.surrogates, X_unit_torch,
            constraint_names=list(self.surrogates.constraint_names),
            objective_name=(self.surrogates.objective_names[0]
                            if self.surrogates.objective_names else None),
            auxiliary_names=list(self.surrogates.auxiliary_names),
            batch_size=1024,
        )
        U_np = X_unit_torch.cpu().numpy()
        def _field(name: str, source: str) -> np.ndarray:
            if source == "analytic":
                return _analytic_field(name, U_np)
            return grid[f"{name}_mean"]
        return np.column_stack([
            _field(spec.x_field, spec.x_field_source),
            _field(spec.y_field, spec.y_field_source),
        ]), grid

    def rank_candidates(
        self,
        iteration: int,
        # Training state: needed to update the KDE.
        X_train_unit: np.ndarray, Y_train: dict[str, np.ndarray],
        feasible: np.ndarray,
        # Candidate sampling.
        sobol_seed: int = 0,
    ) -> dict:
        """Sample a candidate batch, score under entropy+classifier, apply
        the repulsion penalty, and return the best penalised candidate.

        Returns dict with keys:
            X_next                : (1, d) unit-cube tensor of the chosen point.
            active_projection     : name of the projection used for repulsion.
            n_candidates_sampled  : how many candidates went into the batch.
            kappa                 : the repulsion weight used.
            base_log_acq          : the entropy+classifier log-acquisition of X_next.
            log_density           : log rho at X_next's projection coordinate.
            penalised_log_acq     : base - kappa * log_density.
            kde_n_train           : number of training points feeding the KDE.
        """
        spec = self.active_projection(iteration)
        kde = self._maybe_refit_kde(
            spec, iteration, X_train_unit, Y_train, feasible,
        )

        # Sobol candidate batch
        from torch.quasirandom import SobolEngine
        d = X_train_unit.shape[1]
        sob = SobolEngine(dimension=d, scramble=True,
                          seed=sobol_seed + iteration * 1009)
        U = sob.draw(self.config.n_candidates).to(dtype=torch.float64)
        # Filter by joint feasibility prob >= threshold; project to plane
        proj_xy, grid = self._project_candidates(spec, U)
        P_joint = grid["P_cls"].copy()
        for c in self.surrogates.constraint_names:
            P_joint *= grid[f"PF_{c}"]
        # Compute entropy-only base log-acquisition: log H(x) + log P_cls(x)
        # Here H(x) is the binary entropy of the classifier:
        # H(p) = -p*log(p) - (1-p)*log(1-p)
        p = grid["P_cls"]
        eps = 1e-12
        p_clipped = np.clip(p, eps, 1.0 - eps)
        H = -p_clipped * np.log(p_clipped) - (1 - p_clipped) * np.log(1 - p_clipped)
        # Add the joint feasibility (use constraint product as a soft mask)
        log_acq = np.log(np.maximum(H, eps)) + np.log(np.maximum(P_joint, eps))

        # Restrict to P_joint >= threshold and finite projection coords
        valid = (P_joint >= self.config.p_threshold) \
            & np.isfinite(proj_xy).all(axis=1)
        if int(valid.sum()) < 4:
            # Degenerate: return the top base-log_acq candidate without
            # repulsion (no high-confidence feasible candidates).
            idx_top = int(np.argmax(log_acq))
            X_next = U[idx_top:idx_top + 1]
            return {
                "X_next": X_next, "active_projection": spec.name,
                "n_candidates_sampled": self.config.n_candidates,
                "n_above_threshold": int(valid.sum()),
                "kappa": self.config.kappa,
                "base_log_acq": float(log_acq[idx_top]),
                "log_density": float("nan"),
                "penalised_log_acq": float(log_acq[idx_top]),
                "kde_n_train": self._kde_n_train.get(spec.name, 0),
                "status": "no_valid_candidates_no_penalty",
            }

        # Top-K by base log_acq within valid
        log_acq_valid = log_acq[valid]
        order = np.argsort(log_acq_valid)[::-1][:self.config.top_k]
        # Indices into the FULL candidate array
        valid_idx = np.where(valid)[0]
        top_global_idx = valid_idx[order]
        top_proj = proj_xy[top_global_idx]
        top_log_acq = log_acq[top_global_idx]

        # Re-rank with repulsion penalty
        if kde is None:
            # Not enough training points; no penalty
            best = int(np.argmax(top_log_acq))
            chosen = top_global_idx[best]
            return {
                "X_next": U[chosen:chosen + 1],
                "active_projection": spec.name,
                "n_candidates_sampled": self.config.n_candidates,
                "n_above_threshold": int(valid.sum()),
                "kappa": self.config.kappa,
                "base_log_acq": float(top_log_acq[best]),
                "log_density": float("nan"),
                "penalised_log_acq": float(top_log_acq[best]),
                "kde_n_train": self._kde_n_train.get(spec.name, 0),
                "status": "kde_unavailable_no_penalty",
            }

        # Evaluate KDE at candidate projection (log-transform same axes
        # as the KDE was built on).
        log_axes = (spec.x_field in ("h_min", "P_loss", "Q_leak"),
                    spec.y_field in ("h_min", "P_loss", "Q_leak"))
        top_proj_kde = top_proj.astype(np.float64).copy()
        if log_axes[0]:
            top_proj_kde[:, 0] = np.log10(np.clip(top_proj_kde[:, 0], 1e-300, None))
        if log_axes[1]:
            top_proj_kde[:, 1] = np.log10(np.clip(top_proj_kde[:, 1], 1e-300, None))
        with np.errstate(invalid="ignore"):
            log_rho = kde.logpdf(top_proj_kde.T)
        penalised = top_log_acq - self.config.kappa * log_rho
        best = int(np.argmax(penalised))
        chosen = top_global_idx[best]
        return {
            "X_next": U[chosen:chosen + 1],
            "active_projection": spec.name,
            "n_candidates_sampled": self.config.n_candidates,
            "n_above_threshold": int(valid.sum()),
            "kappa": self.config.kappa,
            "base_log_acq": float(top_log_acq[best]),
            "log_density": float(log_rho[best]),
            "penalised_log_acq": float(penalised[best]),
            "kde_n_train": self._kde_n_train.get(spec.name, 0),
            "status": "ok",
        }
